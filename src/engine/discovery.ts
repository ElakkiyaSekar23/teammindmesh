export function discoverMissingUpstream(graph: SupplyChainGraph): DiscoveredLinkSuggestion[] {
  const suggestions: DiscoveredLinkSuggestion[] = [];
  const layer1Suppliers = graph.suppliers.filter((s) => s.layer === 1);

  for (const s1 of layer1Suppliers) {
    const hasUpstream = graph.links.some((l) => l.toId === s1.id);
    if (hasUpstream) {
      continue;
    }

    const haystack = `${s1.name} ${s1.itemSupplied} ${s1.keywords.join(' ')}`.toLowerCase();
    const blueprint =
      DISCOVERY_BLUEPRINTS.find((bp) =>
        bp.matchTokens.some((tok) => haystack.includes(tok)),
      ) ?? DISCOVERY_BLUEPRINTS[0];

    suggestions.push({
      id: `disc-l2-${s1.id}`,
      forLayer1SupplierId: s1.id,
      forLayer1SupplierName: s1.name,
      proposedSupplier: blueprint.layer2,
      proposedLink: {
        toId: s1.id,
        relationship: 'SUPPLIES',
        sharePct: 80,
        transitDays: 2,
        substitutable: !blueprint.layer2.isSingleSource,
      },
      reasonPlain: blueprint.reasonL2,
      confidencePct: blueprint.confidencePct,
    });
  }

  return suggestions;
}
