export function selectNearestCorridorHub(
  lat: number,
  lng: number,
  state: string,
  group: string,
  layer: 2 | 3,
  excludeCity?: string,
): {
  primary: CorridorHub;
  alternates: CorridorHub[];
  distanceKm: number;
} {
  const candidatesForLayer = INDIA_SUPPLY_CORRIDORS.filter(
    (h) => h.layerFocus === layer && h.groups.includes(group),
  );
  const pool =
    candidatesForLayer.length > 0
      ? candidatesForLayer
      : INDIA_SUPPLY_CORRIDORS.filter((h) => h.layerFocus === layer);

  const scored = pool
    .map((hub) => {
      const dist = haversineKm(lat, lng, hub.lat, hub.lng);
      const sameStateBonus =
        state && hub.state.toLowerCase() === state.toLowerCase() ? -45 : 0;
      const sameCityPenalty =
        excludeCity && hub.city.toLowerCase() === excludeCity.toLowerCase() ? 110 : 0;
      return {
        hub,
        dist,
        rankScore: dist + sameStateBonus + sameCityPenalty,
      };
    })
    .sort((a, b) => a.rankScore - b.rankScore);

  const primary = scored[0]?.hub ?? INDIA_SUPPLY_CORRIDORS[0];
  const distanceKm = Math.round(scored[0]?.dist ?? 120);
  const alternates = scored
    .slice(1, 3)
    .map((item) => item.hub);

  return { primary, alternates, distanceKm };
}
